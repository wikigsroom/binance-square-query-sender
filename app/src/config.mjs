import path from 'node:path';
import { fileURLToPath } from 'node:url';

const appRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const projectRoot = path.resolve(appRoot, '..');
const REQUIRED_LUNA_BASE_URL = 'http://43.165.167.179:18241';
const REQUIRED_LUNA_MODEL = 'gpt-6-luna';

function integerEnv(name, fallback, minimum) {
  const value = Number(process.env[name] ?? fallback);
  if (!Number.isInteger(value) || value < minimum) throw new Error(`${name} must be an integer >= ${minimum}`);
  return value;
}

export const config = Object.freeze({
  appRoot,
  projectRoot,
  batchScript: path.join(projectRoot, '.agents', 'skills', 'binance-square-posts', 'scripts', 'batch.mjs'),
  intervalMs: integerEnv('POST_INTERVAL_MINUTES', 15, 1) * 60 * 1000,
  runOnStart: String(process.env.RUN_ON_START ?? 'true').toLowerCase() !== 'false',
  newsMaxLinks: integerEnv('NEWS_MAX_LINKS', 36, 1),
  llmTimeoutMs: integerEnv('LLM_TIMEOUT_MS', 120000, 1000),
  dryRun: String(process.env.DRY_RUN ?? 'false').toLowerCase() === 'true',
  lunaBaseUrl: REQUIRED_LUNA_BASE_URL,
  lunaModel: REQUIRED_LUNA_MODEL,
  lunaReasoningEffort: 'max',
  lunaApiKey: process.env.LUNA_API_KEY ?? '',
});

export function assertConfiguration() {
  if (String(process.env.LOCAL_CONTENT ?? 'false').toLowerCase() === 'true') {
    throw new Error('LOCAL_CONTENT is disabled; every draft must be generated by gpt-6-luna.');
  }
  if (process.env.LUNA_API_BASE_URL && process.env.LUNA_API_BASE_URL.replace(/\/+$/, '') !== REQUIRED_LUNA_BASE_URL) {
    throw new Error(`LUNA_API_BASE_URL must be ${REQUIRED_LUNA_BASE_URL}.`);
  }
  if (process.env.LUNA_API_URL) {
    throw new Error('LUNA_API_URL override is disabled; use the configured gpt-6-luna endpoint.');
  }
  if (process.env.LUNA_MODEL && process.env.LUNA_MODEL !== REQUIRED_LUNA_MODEL) {
    throw new Error(`LUNA_MODEL must be ${REQUIRED_LUNA_MODEL}.`);
  }
  if (!config.lunaApiKey.trim()) {
    throw new Error('LUNA_API_KEY is required in the process environment; it is never read from project files.');
  }
  if (!config.lunaModel.trim()) throw new Error('LUNA_MODEL cannot be empty.');
  if (!config.lunaReasoningEffort.trim()) throw new Error('LUNA_REASONING_EFFORT cannot be empty.');
}

export function resolveProject(relativePath) {
  const resolved = path.resolve(config.projectRoot, relativePath);
  const relative = path.relative(config.projectRoot, resolved);
  if (relative.startsWith('..') || path.isAbsolute(relative)) throw new Error(`Path outside project: ${relativePath}`);
  return resolved;
}

export function relativeToProject(filePath) {
  return path.relative(config.projectRoot, filePath).replaceAll(path.sep, '/');
}
